/**
 * Build the optional Ship extension for `codsh --rust` (ticket 195).
 * Bundles packages/bundle/src/ship-extension-hook.ts into
 * `<out>/hooks/ship-hook.mjs` and writes the `/ship` command it prints to
 * `<out>/commands/ship.md`. `<out>` defaults to packages/cli/extensions/ship,
 * whose manifest, hooks.json, and README are checked in.
 */
import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { build } from 'esbuild'

const root = resolve(import.meta.dirname, '..')
export const SHIP_EXTENSION_SOURCE = join(root, 'packages', 'cli', 'extensions', 'ship')

/** Build into `out` (copying the checked-in files first when out differs). */
export async function buildShipExtension(out = SHIP_EXTENSION_SOURCE) {
  if (resolve(out) !== SHIP_EXTENSION_SOURCE) {
    cpSync(SHIP_EXTENSION_SOURCE, out, {
      recursive: true,
      filter: source => !source.endsWith('ship-hook.mjs') && !source.includes(`${join('ship', 'commands')}`),
    })
  }
  mkdirSync(join(out, 'hooks'), { recursive: true })
  mkdirSync(join(out, 'commands'), { recursive: true })
  const hook = join(out, 'hooks', 'ship-hook.mjs')
  await build({
    entryPoints: [join(root, 'packages', 'bundle', 'src', 'ship-extension-hook.ts')],
    outfile: hook,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    legalComments: 'none',
    banner: { js: '// Generated by scripts/build-ship-extension.mjs from packages/bundle/src/ship-extension*.ts. Do not edit.' },
    logLevel: 'warning',
  })
  const command = execFileSync(process.execPath, [hook, '--print-command'], { encoding: 'utf8' })
  writeFileSync(join(out, 'commands', 'ship.md'), command)
  if (!existsSync(join(out, '.grok-plugin', 'plugin.json'))) throw new Error(`missing Ship extension manifest in ${out}`)
  return out
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = await buildShipExtension(process.argv[2] ? resolve(process.argv[2]) : undefined)
  console.log(`Built the Ship extension at ${out}`)
}
